import type { MetricSeries } from "@/types/metrics";
export type TrafficZone = "Asia/Shanghai" | "UTC";
export type DailyTraffic = {
  up: number | null;
  down: number | null;
  total: number | null;
  partial: boolean;
  lastSample: number | null;
};
export const isTrafficValue = (v: unknown): v is number =>
  typeof v === "number" && Number.isFinite(v) && v >= 0;
export function trafficDayWindow(
  now: number,
  setting: unknown = "Asia/Shanghai",
) {
  const zone: TrafficZone = setting === "UTC" ? "UTC" : "Asia/Shanghai";
  const offset = zone === "UTC" ? 0 : 8 * 3600000;
  const start = Math.floor((now + offset) / 86400000) * 86400000 - offset;
  return {
    start,
    end: now,
    zone,
    label: zone === "UTC" ? "UTC" : "UTC+8",
    key: zone + ":" + start,
  };
}
export function trafficQuota(
  up: unknown,
  down: unknown,
  limit: unknown,
  setting: unknown,
) {
  const requested = typeof setting === "string" ? setting.toLowerCase() : "max";
  const mode = ["up", "down", "sum", "min", "max"].includes(requested)
    ? requested
    : "max";
  let used: number | null = null;
  if (mode === "up" && isTrafficValue(up)) used = up;
  else if (mode === "down" && isTrafficValue(down)) used = down;
  else if (isTrafficValue(up) && isTrafficValue(down))
    used =
      mode === "sum"
        ? up + down
        : mode === "min"
          ? Math.min(up, down)
          : Math.max(up, down);
  const quota = isTrafficValue(limit) && limit > 0 ? limit : null;
  const percent =
    quota !== null && used !== null && Number.isFinite((used / quota) * 100)
      ? (used / quota) * 100
      : null;
  return {
    mode,
    used,
    limit: quota,
    percent,
    bar: percent === null ? null : Math.min(100, Math.max(0, percent)),
    over: quota !== null && used !== null ? Math.max(0, used - quota) : null,
  };
}
function pointTime(value: unknown): number {
  if (typeof value === "number") return value > 1e12 ? value : value * 1000;
  return typeof value === "string" ? Date.parse(value) : NaN;
}
/** traffic.* stores server-generated byte increments. Sum values once; never multiply by count or time. */
export function summarizeDailyTraffic(
  series: MetricSeries[],
  ids: string[],
  start: number,
  end: number,
): Record<string, DailyTraffic> {
  const allowed = new Set(ids);
  type Direction = {
    values: Map<number, number | null>;
    interval: number;
    conflict: boolean;
  };
  const groups = new Map<string, { up: Direction; down: Direction }>();
  const direction = (): Direction => ({
    values: new Map(),
    interval: 60,
    conflict: false,
  });
  for (const id of ids) groups.set(id, { up: direction(), down: direction() });
  for (const s of series) {
    if (
      !allowed.has(s.entity_id) ||
      !["traffic.up", "traffic.down"].includes(s.metric_key) ||
      !Array.isArray(s.points)
    )
      continue;
    const d = groups.get(s.entity_id)![
      s.metric_key === "traffic.up" ? "up" : "down"
    ];
    if (isTrafficValue(s.interval_seconds) && s.interval_seconds > 0)
      d.interval = s.interval_seconds;
    for (const point of s.points) {
      const time = pointTime(point.time);
      if (!Number.isFinite(time) || time < start || time > end) continue;
      const value = isTrafficValue(point.value) ? point.value : null;
      if (d.values.has(time)) {
        if (d.values.get(time) !== value) {
          d.conflict = true;
          d.values.set(time, null);
        }
      } else d.values.set(time, value);
    }
  }
  const sum = (d: Direction) => {
    const all = [...d.values].sort((a, b) => a[0] - b[0]);
    const valid = all.filter((p): p is [number, number] => p[1] !== null);
    const interval = d.interval * 1000;
    const total = valid.length ? valid.reduce((n, p) => n + p[1], 0) : null;
    const partial =
      d.conflict ||
      valid.length === 0 ||
      valid.length !== all.length ||
      (valid[0]?.[0] ?? Infinity) > start + interval ||
      (valid.at(-1)?.[0] ?? -Infinity) < end - Math.max(2 * interval, 120000) ||
      valid.some((p, i) => i > 0 && p[0] - valid[i - 1][0] > interval * 1.5);
    return { total, partial, last: valid.at(-1)?.[0] ?? null };
  };
  return Object.fromEntries(
    [...groups].map(([id, group]) => {
      const up = sum(group.up),
        down = sum(group.down);
      return [
        id,
        {
          up: up.total,
          down: down.total,
          total:
            up.total === null && down.total === null
              ? null
              : (up.total ?? 0) + (down.total ?? 0),
          partial: up.partial || down.partial,
          lastSample: Math.max(up.last ?? 0, down.last ?? 0) || null,
        },
      ];
    }),
  );
}
